/**
 * Generates vectors.h: expected results computed by the TypeScript
 * implementation (contracts + emulator firmware-logic). The C++ firmware
 * library must reproduce them byte for byte.
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { signMessage } from '../../../packages/contracts/src/signing';
import { countsToReading, pulsesToReading } from '../../../tools/emulator/src/firmware-logic';
import { barToCounts } from '../../../tools/emulator/src/plant';

const KEY = '3f1c0a9b2d4e5f60718293a4b5c6d7e8f90a1b2c3d4e5f60718293a4b5c6d7e8';
const c = (s: string) => JSON.stringify(s); // C string literal (JSON escaping is valid C for our ASCII)
const f = (x: number) => (Number.isInteger(x) ? `${x}.0f` : `${x}f`); // C float literal

const tel = { v: 1, deviceId: 'node-inlet', bootId: '1a2b3c4d', seq: 42, ts: 1795363451957, nonce: '0123456789abcdef', intervalMs: 500,
  sensors: { P1: { v: 4.098, raw: 14077, q: 'ok' }, F1: { v: 3.474, raw: 343, q: 'ok' } }, actuators: { pump: { on: true, duty: 100 } },
  diag: { uptimeS: 8, rssi: -52, heapFree: 191230, ntpSynced: true } };
const body = JSON.stringify(tel);
const signed = signMessage(tel, KEY);
const cmd = { v: 1, cmdId: 'mws29yy8-b04bedd09932', deviceId: 'node-inlet', ts: 1795363468353, nonce: 'fedcba9876543210', issuedBy: 'user:admin', type: 'pump.set', params: { on: false } };
const cmdSigned = signMessage(cmd, KEY);
const cmdTampered = cmdSigned.replace('"on":false', '"on":true ');

const counts = [0, 5000, 10923, 14077, 18000, 21845, 26000, 32767];
const pressure = counts.map((n) => countsToReading(n));
const bars = [0, 1.5, 4.1, 7.25, 10];

let h = `// GENERATED by gen-vectors.ts from the TypeScript implementation - do not edit.\n#pragma once\n#include <stdint.h>\n`;
h += `static const char* V_KEY = ${c(KEY)};\n`;
h += `static const char* V_BODY = ${c(body)};\n`;
h += `static const char* V_SIGNED = ${c(signed)};\n`;
h += `static const char* V_CMD_SIGNED = ${c(cmdSigned)};\n`;
h += `static const char* V_CMD_TAMPERED = ${c(cmdTampered)};\n`;
h += `static const char* V_CMD_UNSIGNED = ${c(JSON.stringify(cmd))};\n`;
h += `struct PVec { float counts; int ok; float bar; };\nstatic const PVec V_PRESSURE[] = {\n${counts.map((n, i) => `  {${f(n)}, ${pressure[i]!.q === 'ok' ? 1 : 0}, ${f(pressure[i]!.v ?? 0)}},`).join('\n')}\n};\n`;
h += `struct BVec { float bar; int32_t counts; };\nstatic const BVec V_BAR[] = {\n${bars.map((b) => `  {${f(b)}, ${barToCounts(b)}},`).join('\n')}\n};\n`;
const flows: Array<[number, number, number]> = [[1015, 1000, 0.5], [2000, 1000, 4], [4294967290, 4294967000, 2]];
h += `struct FVec { uint32_t now, prev; float windowS; float lpm; };\nstatic const FVec V_FLOW[] = {\n${flows.map(([a, b, w]) => `  {${a}u, ${b}u, ${f(w)}, ${f(pulsesToReading(a, b, w).v!)}},`).join('\n')}\n};\n`;
writeFileSync(resolve(import.meta.dirname, 'vectors.h'), h);
console.log('wrote vectors.h');
