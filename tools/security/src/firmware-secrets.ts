/**
 * Generates the per-board secrets headers for the ESP32 firmware from the lab
 * secrets (run setup first):
 *
 *   npm run firmware-secrets -w @twin/security -- --ssid MyWifi --wifi-pass xxx --broker 192.168.1.50
 *
 * Writes firmware/include/secrets_node_inlet.h and secrets_node_downstream.h
 * (git-ignored). --broker must be an address listed in the broker certificate:
 * re-run setup with --san <that address> --force if needed.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { parseArgs } from 'node:util';
import forge from 'node-forge';
import { DEVICE_IDS } from '@twin/contracts';

const { values: a } = parseArgs({
  options: {
    ssid: { type: 'string' },
    'wifi-pass': { type: 'string' },
    broker: { type: 'string' },
    port: { type: 'string', default: '8883' },
    ntp: { type: 'string', default: 'pool.ntp.org' },
  },
});
if (!a.ssid || !a['wifi-pass'] || !a.broker) {
  console.error('usage: --ssid <wifi> --wifi-pass <password> --broker <PC LAN IP or hostname> [--port 8883] [--ntp pool.ntp.org]');
  process.exit(1);
}
const REPO = resolve(import.meta.dirname, '../../..');
const S = resolve(REPO, 'secrets');
const creds = JSON.parse(readFileSync(resolve(S, 'mqtt-credentials.json'), 'utf8')) as Record<string, string>;
const keys = JSON.parse(readFileSync(resolve(S, 'device-keys.json'), 'utf8')) as Record<string, string>;
const caPem = readFileSync(resolve(S, 'ca.crt'), 'utf8').trim();

// Check that the broker address is covered by the certificate.
const server = forge.pki.certificateFromPem(readFileSync(resolve(S, 'server.crt'), 'utf8'));
const san = server.getExtension('subjectAltName') as { altNames: Array<{ value?: string; ip?: string }> } | null;
const names = (san?.altNames ?? []).map((n) => n.ip ?? n.value);
if (!names.includes(a.broker)) {
  console.error(`The broker certificate does not cover "${a.broker}" (it covers: ${names.join(', ')}).\n` +
    `Re-run: npm run setup -w @twin/security -- --san ${a.broker} --force   (then restart the broker)`);
  process.exit(1);
}

const esc = (s: string) => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
for (const id of DEVICE_IDS) {
  const file = resolve(REPO, 'firmware/include', `secrets_${id.replace('-', '_')}.h`);
  writeFileSync(
    file,
    `// GENERATED by tools/security/src/firmware-secrets.ts for ${id} - DO NOT COMMIT.
#pragma once
#define WIFI_SSID "${esc(a.ssid)}"
#define WIFI_PASS "${esc(a['wifi-pass'])}"
#define MQTT_HOST "${esc(a.broker)}"
#define MQTT_PORT ${Number(a.port)}
#define MQTT_USER "${id}"
#define MQTT_PASS "${esc(creds[id]!)}"
#define DEVICE_KEY_HEX "${keys[id]}"
#define NTP_SERVER_1 "${esc(a.ntp)}"
#define NTP_SERVER_2 MQTT_HOST
static const char CA_CERT_PEM[] = R"PEM(
${caPem}
)PEM";
`,
    { mode: 0o600 },
  );
  console.log(`wrote ${file}`);
}
